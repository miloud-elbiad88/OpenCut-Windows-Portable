import { describe, expect, test } from "bun:test";
import {
	formatFrameRate,
	getHighestImportedVideoFps,
	getRaisedProjectFpsForImportedMedia,
} from "@/lib/fps/utils";

describe("formatFrameRate", () => {
	test("formats whole frame rates without object coercion", () => {
		expect(formatFrameRate({ numerator: 30, denominator: 1 })).toBe("30 fps");
	});

	test("formats fractional frame rates to two decimals", () => {
		expect(formatFrameRate({ numerator: 30000, denominator: 1001 })).toBe("29.97 fps");
	});

	test("returns a safe fallback for invalid frame rates", () => {
		expect(formatFrameRate({ numerator: 0, denominator: 0 })).toBe("Unknown");
	});
});

describe("getHighestImportedVideoFps", () => {
	test("returns the highest valid video fps", () => {
		expect(
			getHighestImportedVideoFps({
				mediaAssets: [
					{ type: "audio" },
					{ type: "video", fps: 30 },
					{ type: "image", fps: 120 },
					{ type: "video", fps: 60 },
				],
			}),
		).toBe(60);
	});

	test("ignores missing and invalid fps values", () => {
		expect(
			getHighestImportedVideoFps({
				mediaAssets: [
					{ type: "video" },
					{ type: "video", fps: 0 },
					{ type: "video", fps: -10 },
					{ type: "audio", fps: 120 },
				],
			}),
		).toBeNull();
	});
});

describe("getRaisedProjectFpsForImportedMedia", () => {
	test("raises the project fps to match a higher-fps import", () => {
		expect(
			getRaisedProjectFpsForImportedMedia({
				currentFps: { numerator: 30, denominator: 1 },
				importedAssets: [{ type: "video", fps: 60 }],
			}),
		).toEqual({ numerator: 60, denominator: 1 });
	});

	test("does not lower the project fps for lower-fps imports", () => {
		expect(
			getRaisedProjectFpsForImportedMedia({
				currentFps: { numerator: 60, denominator: 1 },
				importedAssets: [{ type: "video", fps: 10 }],
			}),
		).toBeNull();
	});

	test("ignores non-video imports", () => {
		expect(
			getRaisedProjectFpsForImportedMedia({
				currentFps: { numerator: 30, denominator: 1 },
				importedAssets: [
					{ type: "image", fps: 60 },
					{ type: "audio", fps: 120 },
				],
			}),
		).toBeNull();
	});
});
